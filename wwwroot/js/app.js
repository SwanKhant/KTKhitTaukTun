const state = { culture: localStorage.getItem("khittoktun-culture") || "en", portal: null };

function languageKey() {
  return state.culture === "my-MM" ? "my-MM" : "en";
}

function t(key) {
  return translations[languageKey()][key] || translations.en[key] || key;
}

function applyTranslations() {
  document.documentElement.lang = state.culture;
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  document.querySelectorAll("[data-language]").forEach((button) => {
    button.classList.toggle("active", button.dataset.language === state.culture);
  });
}

function setCulture(culture) {
  state.culture = culture === "my-MM" ? "my-MM" : "en";
  localStorage.setItem("khittoktun-culture", state.culture);
  applyTranslations();
  if (state.portal) {
    renderPortal(state.portal);
  }
}

async function api(url, options = {}) {
  const response = await fetch(url, {
    credentials: "same-origin",
    headers: { ...(options.body instanceof FormData ? {} : { "Content-Type": "application/json" }), ...(options.headers || {}) },
    ...options
  });
  if (response.status === 204) return null;
  const body = await response.json().catch(() => ({}));
  if (!response.ok) {
    const error = new Error(body.message || `Request failed (${response.status})`);
    error.status = response.status;
    throw error;
  }
  return body;
}

async function currentUser() {
  return api("/api/auth/me");
}

function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>'"]/g, (character) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", "'": "&#39;", '"': "&quot;" }[character]));
}

function formatDate(value) {
  return new Intl.DateTimeFormat(state.culture === "my-MM" ? "my-MM" : "en-GB", { dateStyle: "medium", timeStyle: "short" }).format(new Date(value));
}

const currencyRates = { USD: 1, EUR: 0.92, GBP: 0.78, MMK: 3500 };
const currencySymbols = { USD: "$", EUR: "€", GBP: "£", MMK: "Ks" };

function money(value, currency = "USD") {
  const amount = Number(value || 0) * (currencyRates[currency] || 1);
  if (currency === "MMK") return `${currencySymbols[currency]} ${Math.round(amount).toLocaleString("en-US")}`;
  return new Intl.NumberFormat(state.culture === "my-MM" ? "my-MM" : "en-US", { style: "currency", currency, maximumFractionDigits: 2 }).format(amount);
}

function showMessage(id, message, type = "error") {
  const element = document.getElementById(id);
  if (!element) return;
  element.textContent = message || "";
  element.classList.toggle("success", type === "success");
  element.classList.toggle("error", type !== "success");
  element.hidden = !message;
}

