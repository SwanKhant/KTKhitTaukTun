async function setupAdmin() {
  if (document.body.dataset.page !== "admin") return;
  const user = await requireUser("Admin");
  if (!user) return;
  try {
    const [dashboard, users] = await Promise.all([api("/api/admin/dashboard"), api("/api/admin/users")]);
    fillSummary(dashboard.summary);
    renderAudit(dashboard.auditLogs);
    renderUsers(users);
  } catch (error) {
    showMessage("admin-error", error.message);
  }

  document.getElementById("summary-form").addEventListener("submit", async (event) => {
    event.preventDefault();
    try {
      const summary = await api("/api/admin/financial-summary", { method: "PUT", body: JSON.stringify({ totalMoney: Number(document.getElementById("summary-total").value), currentFyRevenue: Number(document.getElementById("summary-current").value), lastFyRevenue: Number(document.getElementById("summary-last").value), dueAmount: Number(document.getElementById("summary-due").value), isDuePaid: document.getElementById("summary-paid").checked }) });
      fillSummary(summary);
      showMessage("admin-result", t("saveFinancialValues"), "success");
    } catch (error) { showMessage("admin-error", error.message); }
  });

  document.getElementById("user-form").addEventListener("submit", async (event) => {
    event.preventDefault();
    try {
      await api("/api/admin/users", { method: "POST", body: JSON.stringify({ displayName: document.getElementById("user-name").value, email: document.getElementById("user-email").value, temporaryPassword: document.getElementById("user-password").value }) });
      event.target.reset();
      renderUsers(await api("/api/admin/users"));
      showMessage("admin-result", t("createShareholderAccount"), "success");
    } catch (error) { showMessage("admin-error", error.message); }
  });

  document.getElementById("csv-form").addEventListener("submit", async (event) => {
    event.preventDefault();
    const file = document.getElementById("csv-file").files[0];
    if (!file) return;
    const formData = new FormData();
    formData.append("file", file);
    try {
      const result = await api("/api/admin/import-financials", { method: "POST", body: formData });
      event.target.reset();
      showMessage("admin-result", result.message, "success");
      renderUsers(await api("/api/admin/users"));
    } catch (error) { showMessage("admin-error", error.message); }
  });

  document.getElementById("csv-template").addEventListener("click", () => {
    const csv = "Email,DisplayName,TemporaryPassword,FinancialYear,TotalMoney,Revenue,DueAmount,IsDuePaid\nshareholder@example.com,Example Shareholder,ChangeMe123!,FY2026-27,100000,50000,5000,false\n";
    const link = document.createElement("a");
    link.href = URL.createObjectURL(new Blob([csv], { type: "text/csv" }));
    link.download = "financial-import-template.csv";
    link.click();
    URL.revokeObjectURL(link.href);
  });
}

